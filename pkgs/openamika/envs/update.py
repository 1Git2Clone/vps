"""Regenerate the locked Python environments from the pinned upstream tree.

    nix build .#openamika-source && python3 pkgs/openamika/envs/update.py result

Writes envs/<name>/pyproject.toml from upstream's own requirement files and
torch pins, then `uv lock`s each one. Run it after bumping the revision in
../default.nix, and commit what changes. Never edit the generated files.
"""

import ast
import re
import subprocess
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
CPU_INDEX = "https://download.pytorch.org/whl/cpu"


def requirements(path):
    out = []
    for line in path.read_text().splitlines():
        line = line.split("#", 1)[0].strip()
        if line:
            out.append(line)
    return out


def must(pattern, text):
    match = re.search(pattern, text, re.M)
    if match is None:
        raise SystemExit(f"upstream no longer matches {pattern!r}; update update.py")
    return match.group(1)


def torch_pin(source, script, name):
    """TORCH_VERSION / TORCH_PINS exactly as upstream's setup script states them.

    TORCH_PINS names TORCH_VERSION as a variable, so it is evaluated rather
    than pattern-matched: a missed torch pin falls through to PyPI's CUDA
    build, several GB of libraries a CPU-only box never loads.
    """
    text = (source / "scripts" / script).read_text()
    version = must(r'^TORCH_VERSION = "([\d.]+)"', text)
    if name == "core":
        pins = ast.literal_eval(must(r"^TORCH_PINS = (\{.*\})", text).replace("TORCH_VERSION", repr(version)))
        return {k: v for k, v in pins.items() if k != "torchvision"}
    return {"torch": version, "torchaudio": version}


def write(name, deps, torch):
    folder = HERE / name
    folder.mkdir(exist_ok=True)
    # Upstream's unpinned `torch>=2.0` lines yield to its own exact pins.
    deps = [d for d in deps if not re.match(r"torch(audio)?\b", d)]
    deps += [f"{pkg}=={ver}" for pkg, ver in sorted(torch.items())]
    lines = [
        "# GENERATED by update.py from the pinned OpenAmika source. Do not edit.",
        "[project]",
        f'name = "openamika-{name}"',
        'version = "0"',
        'requires-python = "==3.11.*"',
        "dependencies = [",
        *(f'  "{d}",' for d in deps),
        "]",
        "",
        "[tool.uv]",
        'environments = ["sys_platform == \'linux\' and platform_machine == \'x86_64\'"]',
        "",
        "[[tool.uv.index]]",
        'name = "pytorch-cpu"',
        f'url = "{CPU_INDEX}"',
        "explicit = true",
        "",
        "[tool.uv.sources]",
        *(f'{pkg} = {{ index = "pytorch-cpu" }}' for pkg in sorted(torch)),
        "",
    ]
    (folder / "pyproject.toml").write_text("\n".join(lines))
    subprocess.run(["uv", "lock", "--python", "3.11", "--directory", str(folder)], check=True)


def main(source):
    source = Path(source)
    core = torch_pin(source, "setup_core.py", "core")
    voice = torch_pin(source, "setup_tts.py", "voice")
    write("brain", requirements(source / "brain/requirements.txt"), {})
    write("speech", requirements(source / "speech/requirements.txt"), core)
    write("embed", requirements(source / "brain/requirements-embedder.txt"), core)
    write("voice", requirements(source / "vendor/tts-engine/requirements-tts.txt"), voice)


if __name__ == "__main__":
    main(sys.argv[1])
