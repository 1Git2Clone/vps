"""Write each pack's full mod list into the handbook, from the pack itself.

usage: python3 -I packs/mod-list.py

For every packs/mc<N>, writes docs/src/minecraft/worlds/mc<N>-mods.md: what
the server runs (so every player experiences it) and what only the players'
pack adds, each linked to its Modrinth project. The world pages include these
with mdBook's {{#include}}, so the prose is written by hand and the list never
is: a hand-kept list goes stale the first time someone runs `packwiz update`.

Then it checks the handbook's download links: every .mrpack link, and the
Minecraft version beside it, must match what packs/default.nix builds. Those
are written by hand, so it fails and names each stale line rather than
rewriting them.

Run by the mod-lists pre-commit hook. Like packwiz refresh, it only writes a
file whose content changed, and pre-commit stops the commit when it did.
"""
import pathlib
import re
import sys
import textwrap
import tomllib
import unicodedata

root = pathlib.Path(__file__).resolve().parent
docs = root.parent / "docs" / "src" / "minecraft" / "worlds"

KIND = {"mods": "mod", "resourcepacks": "resource pack", "shaderpacks": "shader"}
WHERE = {"both": "server and you", "server": "server only", "client": "you"}


def table(rows):
    """A markdown table, padded so markdownlint's aligned style passes."""
    head = ["Name", "Kind", "Runs on"]
    widths = [max(len(r[i]) for r in [head, *rows]) for i in range(3)]
    line = lambda r: "| " + " | ".join(c.ljust(w) for c, w in zip(r, widths)) + " |"
    return "\n".join([line(head), "| " + " | ".join("-" * w for w in widths) + " |", *map(line, rows)])


def wrap(text):
    return "\n".join(textwrap.wrap(text, 80, break_on_hyphens=False))


def plain(name):
    """Drop emoji and other symbols ("Jade 🔍"): markdownlint counts them two
    columns wide, so a table holding one can never pass its alignment rule."""
    return "".join(c for c in name if unicodedata.category(c) != "So").strip()


def section(title, intro, rows):
    if not rows:
        return ""
    return f"### {title}\n\n{wrap(intro)}\n\n{table(rows)}\n"


for pack_toml in sorted(root.glob("mc*/pack.toml")):
    pack = pack_toml.parent
    meta = tomllib.loads(pack_toml.read_text())
    server, client = [], []
    for kind in KIND:
        for f in sorted((pack / kind).glob("*.pw.toml")) if (pack / kind).exists() else []:
            m = tomllib.loads(f.read_text())
            side = m.get("side", "both")
            name = plain(m["name"]).replace("|", "\\|")
            link = f"[{name}](https://modrinth.com/project/{m['update']['modrinth']['mod-id']})"
            row = [link, KIND[kind], WHERE[side]]
            (client if side == "client" else server).append(row)
    key = lambda r: r[0].lower()
    server.sort(key=key)
    client.sort(key=key)

    out = "\n".join(
        part
        for part in [
            # Included into a page, so it starts mid-page, not with a heading.
            "<!-- markdownlint-disable-file MD041 -->\n",
            f"<!-- Generated by packs/mod-list.py from packs/{pack.name}. Do not edit:\n"
            "     change the pack, and the pre-commit hook rewrites this. -->\n",
            wrap(
                f"Minecraft **{meta['versions']['minecraft']}**, Fabric loader "
                f"{meta['versions']['fabric']}: {len(server)} on the server, "
                f"{len(client)} more in your pack only."
            )
            + "\n",
            section(
                "On the server",
                "Everyone on the world gets these. `server only` ones change the "
                "world without needing anything on your side.",
                server,
            ),
            section(
                "In your pack only",
                "Performance, interface and visuals. Nobody else sees them, and "
                "the world works without them.",
                client,
            ),
        ]
        if part
    )
    target = docs / f"{pack.name}-mods.md"
    target.parent.mkdir(parents=True, exist_ok=True)
    if not target.exists() or target.read_text() != out:
        target.write_text(out)
        print(f"wrote {target.relative_to(root.parent)}")


# The download links. Each .mrpack is named after its pack and its Minecraft
# version (packs/default.nix), so a link written by hand goes stale with every
# version bump. Not rewritten here: the links sit in aligned tables, and a new
# width means re-padding prose tables. Failing names each line to fix instead.

repo = root.parent
names = dict(re.findall(r'(mc\d+) = pack "mc\d+" "([^"]+)"', (root / "default.nix").read_text()))
mc = {
    p.parent.name: tomllib.loads(p.read_text())["versions"]["minecraft"]
    for p in root.glob("mc*/pack.toml")
}
link = re.compile(r"\[([^\]]*\.mrpack)\]\(https://pages\.hu-tao\.dev/hutao/vps/(mc\d+)/([^)]*)\)")
stale = []
pages = [repo / "README.md", *sorted((repo / "docs" / "src").rglob("*.md"))]
for page in pages:
    if re.fullmatch(r"mc\d+-mods\.md", page.name):
        continue
    where = page.relative_to(repo)
    for n, line in enumerate(page.read_text().splitlines(), 1):
        for text, key, path in link.findall(line):
            # Either build of the pack: plain, or -with-options.
            want = f"{names[key]}-{mc[key]}.mrpack"
            wanted = (want, want.replace(".mrpack", "-with-options.mrpack"))
            if text != path or text not in wanted:
                stale.append(f"{where}:{n}: {key}'s packs are {' and '.join(wanted)}")
            # A world table's row carries the version in a cell of its own.
            if line.startswith("|") and f"| {mc[key]} " not in line:
                stale.append(f"{where}:{n}: {key} is on Minecraft {mc[key]}")
    world = re.fullmatch(r"(mc\d+)\.md", page.name)
    if world and world[1] in mc:
        found = re.search(r"^\*\*Minecraft\*\* (\S+)$", page.read_text(), re.M)
        if found and found[1] != mc[world[1]]:
            stale.append(f"{where}: {world[1]} is on Minecraft {mc[world[1]]}, the page says {found[1]}")
if stale:
    print("handbook out of step with the packs:", *stale, sep="\n  ", file=sys.stderr)
    sys.exit(1)
